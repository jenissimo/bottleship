import { afterEach, beforeEach, expect, test } from 'bun:test';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const source = fileURLToPath(new URL('../bench-v86/call-abi/', import.meta.url));
const modules = Object.keys(JSON.parse(readFileSync(join(source, 'expected.json'), 'utf8')).modules);
let fixture: string;
beforeEach(() => {
    fixture = mkdtempSync(join(tmpdir(), 'bottleship-call-abi-'));
    cpSync(source, fixture, { recursive: true });
});
afterEach(() => rmSync(fixture, { recursive: true, force: true }));

function run(args = ['--check'], status = 0) {
    const result = spawnSync('node', [join(fixture, 'bench.mjs'), ...args], { encoding: 'utf8', timeout: 10_000 });
    expect(result.error).toBeUndefined();
    expect(result.signal).toBeNull();
    expect(result.status).toBe(status);
    if (status !== 0) expect(result.stdout).not.toContain('module bytes match expected.json');
    return result;
}
function alterExpected(change: (value: any) => void) {
    const path = join(fixture, 'expected.json');
    const expected = JSON.parse(readFileSync(path, 'utf8'));
    change(expected);
    writeFileSync(path, JSON.stringify(expected));
}

test('call ABI check verifies all arms against the committed artifacts', () => {
    expect(run().stdout).toContain('state checks pass for 7 arms');
});
test('missing expected state fails checking and timed runs', () => {
    rmSync(join(fixture, 'expected.json'));
    expect(run(['--check'], 1).stderr).toContain('expected.json is missing');
    expect(run(['--rounds', '1', '--n', '1', '--warmup', '0'], 1).stderr).toContain('expected.json is missing');
});
test.each(modules)('missing module %s fails checking', name => {
    rmSync(join(fixture, 'wasm', name + '.wasm'));
    expect(run(['--check'], 1).stderr).toContain(`wasm/${name}.wasm is missing`);
});
test('missing all artifacts cannot report successful verification', () => {
    rmSync(join(fixture, 'expected.json'));
    rmSync(join(fixture, 'wasm'), { recursive: true });
    const result = run(['--check'], 1);
    expect(result.stderr).toContain('expected.json is missing');
    for (const name of modules) expect(result.stderr).toContain(`wasm/${name}.wasm is missing`);
});
test('a corrupted expected hash fails checking', () => {
    alterExpected(value => { value.modules.leaves = '0'.repeat(64); });
    expect(run(['--check'], 1).stderr).toContain('generated bytes differ from expected.json');
});
test('corrupted Wasm bytes fail checking', () => {
    const path = join(fixture, 'wasm', 'leaves.wasm');
    const bytes = readFileSync(path);
    bytes[0] ^= 1;
    writeFileSync(path, bytes);
    expect(run(['--check'], 1).stderr).toContain('wasm/leaves.wasm differs from the generated module');
});
test.each(['value', 'calls', 'missing'])('corrupted expected state (%s) fails checking', kind => {
    alterExpected(value => {
        if (kind === 'value') value.states[0].state[0]++;
        else if (kind === 'calls') value.states[0].calls++;
        else value.states.pop();
    });
    expect(run(['--check'], 1).stderr).toContain('expected.json');
});
test('regeneration works without artifacts and repairs a stale expectation', () => {
    rmSync(join(fixture, 'expected.json'));
    rmSync(join(fixture, 'wasm'), { recursive: true });
    run(['--write-expected']);
    expect(existsSync(join(fixture, 'expected.json'))).toBe(true);
    run(['--emit', 'wasm']);
    run();
    alterExpected(value => { value.modules.leaves = 'stale'; });
    run(['--write-expected']);
    run();
});
test('a timing smoke checks every run after artifact verification', () => {
    const output = join(fixture, 'smoke.json');
    const result = run(['--rounds', '2', '--n', '1000,2000', '--warmup', '1', '--json', output]);
    expect(result.stdout).toContain('all 56 runs match');
    expect(JSON.parse(readFileSync(output, 'utf8')).raw).toHaveLength(28);
});
