/** VK → DirectInput DIK scan-code mapping (shared by dinput HLE and InputManager buffering). */

const VK_TO_DIK: Record<number, number> = {
    0x08: 0x0E, // VK_BACK -> DIK_BACK
    0x09: 0x0F, // VK_TAB -> DIK_TAB
    0x0D: 0x1C, // VK_RETURN -> DIK_RETURN
    0x14: 0x3A, // VK_CAPITAL -> DIK_CAPITAL
    0x1B: 0x01, // VK_ESCAPE -> DIK_ESCAPE
    0x20: 0x39, // VK_SPACE -> DIK_SPACE
    0x21: 0xC9, // VK_PRIOR -> DIK_PRIOR
    0x22: 0xD1, // VK_NEXT -> DIK_NEXT
    0x23: 0xCF, // VK_END -> DIK_END
    0x24: 0xC7, // VK_HOME -> DIK_HOME
    0x25: 0xCB, // VK_LEFT -> DIK_LEFT
    0x26: 0xC8, // VK_UP -> DIK_UP
    0x27: 0xCD, // VK_RIGHT -> DIK_RIGHT
    0x28: 0xD0, // VK_DOWN -> DIK_DOWN
    0x2D: 0xD2, // VK_INSERT -> DIK_INSERT
    0x2E: 0xD3, // VK_DELETE -> DIK_DELETE
    0x70: 0x3B, // VK_F1 -> DIK_F1
    0x71: 0x3C, // VK_F2 -> DIK_F2
    0x72: 0x3D, // VK_F3 -> DIK_F3
    0x73: 0x3E, // VK_F4 -> DIK_F4
    0x74: 0x3F, // VK_F5 -> DIK_F5
    0x75: 0x40, // VK_F6 -> DIK_F6
    0x76: 0x41, // VK_F7 -> DIK_F7
    0x77: 0x42, // VK_F8 -> DIK_F8
    0x78: 0x43, // VK_F9 -> DIK_F9
    0x79: 0x44, // VK_F10 -> DIK_F10
    0x7A: 0x57, // VK_F11 -> DIK_F11
    0x7B: 0x58, // VK_F12 -> DIK_F12
    0xA0: 0x2A,
    0xA1: 0x36,
    0xA2: 0x1D,
    0xA3: 0x9D,
    0xA4: 0x38,
    0xA5: 0xB8
};

const VK_TO_DIK_ALPHANUM: Array<[number, number]> = [
    [0x30, 0x0B], [0x31, 0x02], [0x32, 0x03], [0x33, 0x04], [0x34, 0x05],
    [0x35, 0x06], [0x36, 0x07], [0x37, 0x08], [0x38, 0x09], [0x39, 0x0A],
    [0x41, 0x1E], [0x42, 0x30], [0x43, 0x2E], [0x44, 0x20], [0x45, 0x12],
    [0x46, 0x21], [0x47, 0x22], [0x48, 0x23], [0x49, 0x17], [0x4A, 0x24],
    [0x4B, 0x25], [0x4C, 0x26], [0x4D, 0x32], [0x4E, 0x31], [0x4F, 0x18],
    [0x50, 0x19], [0x51, 0x10], [0x52, 0x13], [0x53, 0x1F], [0x54, 0x14],
    [0x55, 0x16], [0x56, 0x2F], [0x57, 0x11], [0x58, 0x2D], [0x59, 0x15],
    [0x5A, 0x2C]
];

/** Reverse DIK → VK map for action-mapped GetDeviceData. */
export const DIK_TO_VK: Record<number, number> = (() => {
    const m: Record<number, number> = {};
    for (const vkStr of Object.keys(VK_TO_DIK)) {
        const vk = Number(vkStr);
        m[VK_TO_DIK[vk]] = vk;
    }
    for (const [vk, dik] of VK_TO_DIK_ALPHANUM) m[dik] = vk;
    const numpadDik = [0x52, 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49];
    for (let i = 0; i < numpadDik.length; i++) m[numpadDik[i]] = 0x60 + i;
    return m;
})();

export function vkToDik(vk: number): number | null {
    if (VK_TO_DIK[vk] !== undefined) return VK_TO_DIK[vk];
    for (const [vkCode, dik] of VK_TO_DIK_ALPHANUM) {
        if (vkCode === vk) return dik;
    }
    if (vk >= 0x60 && vk <= 0x69) {
        const numpad = [0x52, 0x4F, 0x50, 0x51, 0x4B, 0x4C, 0x4D, 0x47, 0x48, 0x49];
        return numpad[vk - 0x60];
    }
    return null;
}
