/**
 * The flat d3dx9 effect pass-state table: a compiled effect encodes each state assignment as an
 * `operation` integer, and that integer is a direct INDEX into this table, not an enum value.
 * Ids are therefore dense 0x00..0xB2 with no gaps — any reordering or omission silently
 * remaps every effect in the wild. Transcribed from Wine's d3dx9_36 state_table[] and
 * cross-checked against vkd3d's fx_2_pass_states[].
 *
 * `op` is resolved to its numeric value; what it MEANS depends on `cls` — a D3D enum for the
 * render/texture-stage/sampler/transform classes, an index into the sub-enums below for
 * Material, Light and ShaderConst, and meaningless (0) for the classes whose id is the whole
 * identity (Fvf, NPatchMode, Texture, SetSampler, VertexShader, PixelShader, LightEnable).
 */

/** Wine's STATE_CLASS, in its order so the numbering cross-reads. */
export const enum EffectStateClass {
    LightEnable = 0,
    Fvf = 1,
    Light = 2,
    Material = 3,
    NPatchMode = 4,
    PixelShader = 5,
    RenderState = 6,
    SetSampler = 7,
    SamplerState = 8,
    Texture = 9,
    TextureStage = 10,
    Transform = 11,
    VertexShader = 12,
    ShaderConst = 13,
    Unknown = 14,
}

