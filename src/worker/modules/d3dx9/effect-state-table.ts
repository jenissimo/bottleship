/** null rather than a clamped entry: an out-of-range id is a corrupt effect the caller must refuse. */
export function effectStateInfo(id: number): EffectStateInfo | null {
    if (!Number.isInteger(id) || id < 0 || id >= EFFECT_STATE_TABLE.length) return null;
    return EFFECT_STATE_TABLE[id]!;
}
